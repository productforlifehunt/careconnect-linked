export function searchCnCities(query: string, limit = 10): CnCity[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return CN_CITIES.filter(c =>
    c.name.includes(q) ||
    c.pinyin.startsWith(q) ||
    c.zip.startsWith(q) ||
    c.province.includes(q)
  ).slice(0, limit);
}
